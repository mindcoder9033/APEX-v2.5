export function getCarsByManufacturer(manufacturer: string): string[] {
  return FM23_CARS_BY_MAKE[manufacturer] || [];
}

export function findCarByFullName(fullName: string): FM23Car | undefined {
  if (!fullName) return undefined;
  const lower = fullName.toLowerCase().trim();
  return FM23_CARS.find(c => c.fullName.toLowerCase() === lower || lower.includes(c.model.toLowerCase()));
}

export function parseCarName(rawCarName?: string): { manufacturer: string; model: string; fullName: string } | null {
  if (!rawCarName) return null;
  const clean = rawCarName.trim();
  const exact = FM23_CARS.find(c => c.fullName.toLowerCase() === clean.toLowerCase());
  if (exact) {
    return { manufacturer: exact.manufacturer, model: exact.fullName, fullName: exact.fullName };
  }
  // Try matching make prefix
  for (const make of FM23_MANUFACTURERS) {
    if (clean.toLowerCase().startsWith(make.toLowerCase())) {
      const matchedCar = FM23_CARS_BY_MAKE[make]?.find(c => c.toLowerCase().includes(clean.toLowerCase()) || clean.toLowerCase().includes(c.toLowerCase()));
      if (matchedCar) {
        return { manufacturer: make, model: matchedCar, fullName: matchedCar };
      }
      return { manufacturer: make, model: clean, fullName: clean };
    }
  }
  return null;
}
